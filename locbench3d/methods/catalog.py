def get_method(name: str) -> MethodDefinition:
    if name not in METHOD_CATALOG:
        raise KeyError(f"Unknown method {name!r}. Known: {sorted(METHOD_CATALOG)}")
    return METHOD_CATALOG[name]


_APPLICABILITY_METRICS = (
    "anchor_count",
    "satellite_count",
    "rtk_convergence",
    "ppp_convergence",
    "radio_airtime",
    "correction_link_traffic",
)


def applicability_matrix() -> dict[str, dict[str, bool]]:
    """Which scalability/GNSS-specific metrics apply to which method."""
    matrix: dict[str, dict[str, bool]] = {}
    for name, m in METHOD_CATALOG.items():
        matrix[name] = {
            "anchor_count": m.is_local_radio_anchor_based,
            "satellite_count": m.is_gnss,
            "rtk_convergence": m.is_rtk,
            "ppp_convergence": m.is_ppp,
            "radio_airtime": m.uses_active_radio_airtime,
            "correction_link_traffic": m.uses_correction_link,
        }
    return matrix
