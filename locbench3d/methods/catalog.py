"""Method catalog and applicability matrix.

Each entry records the mathematical minimum anchor/satellite count
separately from the preferred benchmark count, and whether this project
has a native simulator for the method or relies on sourced/imported
evidence (measured, published, or official) instead. Per the requirements,
not every method gets a bespoke simulator: methods without one are
compared using imported evidence, and that fact is recorded here rather
than papered over with an invented model.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Optional


@dataclass(frozen=True)
class MethodDefinition:
    name: str
    family: str  # "LOCAL_RADIO" | "GNSS" | "OTHER"
    display_name: str
    mathematical_minimum_anchors: Optional[int]
    preferred_benchmark_anchors: Optional[int]
    has_native_simulator: bool
    evidence_note: str = ""
    is_local_radio_anchor_based: bool = False
    is_gnss: bool = False
    is_rtk: bool = False
    is_ppp: bool = False
    uses_active_radio_airtime: bool = False
    uses_correction_link: bool = False


def _local(
    name,
    display_name,
    math_min,
    preferred,
    has_sim,
    note="",
    airtime=True,
) -> MethodDefinition:
    return MethodDefinition(
        name=name,
        family="LOCAL_RADIO",
        display_name=display_name,
        mathematical_minimum_anchors=math_min,
        preferred_benchmark_anchors=preferred,
        has_native_simulator=has_sim,
        evidence_note=note,
        is_local_radio_anchor_based=math_min is not None,
        uses_active_radio_airtime=airtime,
    )


