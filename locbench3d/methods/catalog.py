def _gnss(name, display_name, is_rtk=False, is_ppp=False) -> MethodDefinition:
    return MethodDefinition(
        name=name,
        family="GNSS",
        display_name=display_name,
        mathematical_minimum_anchors=None,
        preferred_benchmark_anchors=None,
        has_native_simulator=False,
        evidence_note=(
            "GNSS results are imported from receiver logs or official/"
            "published sources (see gnss.model), not generated by a project "
            "GNSS signal simulator."
        ),
        is_gnss=True,
        is_rtk=is_rtk,
        is_ppp=is_ppp,
        uses_correction_link=is_rtk or is_ppp,
    )


